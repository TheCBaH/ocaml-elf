#!/bin/sh
# Regenerates test/fixtures/<arch>/{obj.o,static,dynamic,lib.so} and the recorded readelf output
# with the cross toolchains, and writes test/fixtures/PROVENANCE. Run by hand from the repository
# root after changing a source or a toolchain; CI never runs it, and the tests need none of these
# tools: they read the checked-in files.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
fix="$root/test/fixtures"
rv32_bin=/usr/local/riscv32-linux-gnu-toolchain/bin

# arch dir | gcc | extra flags | flag that makes GCC emit .note.gnu.property (empty: none)
archs="
x86-32|i686-linux-gnu||-fcf-protection=full
x86-64|x86_64-linux-gnu||-fcf-protection=full
arm|arm-linux-gnueabihf|-march=armv7-a -mfpu=vfpv3-d16 -marm|
aarch64|aarch64-linux-gnu||-mbranch-protection=standard
riscv32|$rv32_bin/riscv32-linux-gnu|-march=rv32imafd -mabi=ilp32d|
riscv64|riscv64-linux-gnu|-march=rv64imafd -mabi=lp64d|
"

common="-O1 -nostdlib -ffreestanding -fno-asynchronous-unwind-tables -fno-stack-protector"
link="-Wl,-z,max-page-size=0x1000 -Wl,-z,common-page-size=0x1000 -Wl,-z,noseparate-code -Wl,--build-id=sha1"

: > "$fix/PROVENANCE.new"
echo "$archs" | while IFS='|' read -r dir prefix flags noteflag; do
  [ -n "$dir" ] || continue
  out="$fix/$dir"
  mkdir -p "$out"
  cc="$prefix-gcc"
  # shellcheck disable=SC2086
  $cc $common $flags -c "$fix/src/obj.c" -o "$out/obj.o"
  # shellcheck disable=SC2086
  $cc $common $flags -static $link -Wl,-e,_start "$fix/src/static.c" -o "$out/static"
  # shellcheck disable=SC2086
  $cc $common $flags -shared -fPIC $link -Wl,-soname,lib.so "$fix/src/lib.c" -o "$out/lib.so"
  # shellcheck disable=SC2086
  $cc $common $flags -no-pie $link -Wl,-e,_start -Wl,-dynamic-linker,/lib/ld.so.1 -Wl,-rpath,'$ORIGIN' \
    "$fix/src/dyn.c" "$out/lib.so" -o "$out/dynamic"
  # Edge cases: an 8-aligned .note.gnu.property (object and static executable), and an object with
  # a COMDAT section group assembled by GAS.
  files="obj.o static dynamic lib.so group.o"
  if [ -n "$noteflag" ]; then
    # shellcheck disable=SC2086
    $cc $common $flags $noteflag -c "$fix/src/obj.c" -o "$out/note.o"
    # shellcheck disable=SC2086
    $cc $common $flags $noteflag -static $link -Wl,-e,_start "$fix/src/static.c" -o "$out/note-static"
    files="$files note.o note-static"
  fi
  case "$dir" in
    arm|aarch64) progbits='%progbits' ;;
    *) progbits='@progbits' ;;
  esac
  printf '\t.section .text.grp,"axG",%s,grpsym,comdat\n\t.globl grpsym\ngrpsym:\tnop\n\t.section .data.grp,"awG",%s,grpsym,comdat\n\t.word 1\n' \
    "$progbits" "$progbits" > "$out/group.s"
  "$prefix-as" $(case "$dir" in arm) echo -march=armv7-a ;; riscv32) echo -march=rv32imafd -mabi=ilp32d ;; riscv64) echo -march=rv64imafd -mabi=lp64d ;; x86-32) echo --32 ;; esac) \
    "$out/group.s" -o "$out/group.o"
  rm -f "$out/group.s"
  readelf="$prefix-readelf"
  for f in $files; do
    "$readelf" -W -a "$out/$f" > "$out/$f.readelf" 2>&1 || true
    sha=$(sha256sum "$out/$f" | cut -d' ' -f1)
    echo "$dir/$f $sha" >> "$fix/PROVENANCE.new"
  done
  {
    echo "== $dir"
    echo "compiler: $($cc --version | head -1)"
    echo "linker: $("$prefix-ld" --version | head -1)"
    echo "compile: $cc $common $flags -c src/obj.c"
    echo "static:  $cc $common $flags -static $link -Wl,-e,_start src/static.c"
    echo "lib.so:  $cc $common $flags -shared -fPIC $link -Wl,-soname,lib.so src/lib.c"
    echo "dynamic: $cc $common $flags -no-pie $link -Wl,-e,_start -Wl,-dynamic-linker,/lib/ld.so.1 -Wl,-rpath,\$ORIGIN src/dyn.c lib.so"
    [ -z "$noteflag" ] || echo "note:    the obj/static commands again with $noteflag"
    echo "group:   $prefix-as of a COMDAT section-group source (see the script)"
  } >> "$fix/PROVENANCE.tools"
done

{
  echo "Generated by tools/regen-fixtures.sh from test/fixtures/src."
  echo "Do not edit by hand; regenerate."
  echo
  cat "$fix/PROVENANCE.tools"
  echo
  echo "SHA-256 of each checked-in file:"
  cat "$fix/PROVENANCE.new"
} > "$fix/PROVENANCE"
rm -f "$fix/PROVENANCE.new" "$fix/PROVENANCE.tools"
